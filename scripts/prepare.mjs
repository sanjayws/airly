import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
// Preserve one shared implementation as literal frontend source even when
// Wrangler reformats the backend function during bundling.
const source=await readFile('lib/alerts.js','utf8');
const code=source.slice(source.indexOf('export function alertTransition')).replace(/^export /,'').trim();
await writeFile('data/alert-source.js','// Generated by scripts/prepare.mjs from lib/alerts.js.\nexport default '+JSON.stringify(code)+';\n');
const hash=createHash('sha256');
for(const file of ['worker.js','ui/app.js','lib/alerts.js','lib/air-quality.js','lib/geo.js','data/countries.js','data/leaflet.js','wrangler.toml'])hash.update(file).update(await readFile(file));
await writeFile('data/release.js','// Generated from deployment sources by scripts/prepare.mjs.\nexport default '+JSON.stringify(hash.digest('hex').slice(0,16))+';\n');
